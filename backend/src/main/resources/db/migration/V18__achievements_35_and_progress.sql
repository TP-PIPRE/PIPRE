CREATE TABLE gamification_accounts (
    student_id VARCHAR(36) PRIMARY KEY REFERENCES users(id_user) ON DELETE CASCADE,
    legacy_xp INTEGER NOT NULL DEFAULT 0 CHECK(legacy_xp >= 0),
    legacy_level INTEGER NOT NULL DEFAULT 1 CHECK(legacy_level >= 1),
    earned_xp INTEGER NOT NULL DEFAULT 0 CHECK(earned_xp >= 0)
);
-- Membership rows may mirror the same balance: MAX preserves it once, never SUM.
INSERT INTO gamification_accounts(student_id,legacy_xp,legacy_level)
SELECT u.id_user,GREATEST(COALESCE(MAX(gs.xp_total),0),0),GREATEST(COALESCE(MAX(gs.level),1),1)
FROM users u LEFT JOIN group_students gs ON gs.id_student=u.id_user GROUP BY u.id_user;

CREATE TABLE game_level_progress (
    student_id VARCHAR(36) NOT NULL REFERENCES users(id_user) ON DELETE CASCADE,
    game VARCHAR(20) NOT NULL CHECK(game IN ('neonflow','tetrilogic')),
    level_number INTEGER NOT NULL CHECK(level_number BETWEEN 1 AND 30),
    best_stars INTEGER NOT NULL CHECK(best_stars BETWEEN 1 AND 3),
    first_completed_at TIMESTAMP WITH TIME ZONE NOT NULL,
    last_completed_at TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY(student_id,game,level_number)
);

CREATE TABLE daily_challenges (
    local_date DATE PRIMARY KEY,
    game VARCHAR(20) NOT NULL CHECK(game IN ('neonflow','tetrilogic')),
    level_number INTEGER NOT NULL CHECK(level_number BETWEEN 1 AND 30),
    level_template VARCHAR(40) NOT NULL,
    time_zone VARCHAR(40) NOT NULL DEFAULT 'America/Lima'
);
CREATE TABLE daily_challenge_completions (
    student_id VARCHAR(36) NOT NULL REFERENCES users(id_user) ON DELETE CASCADE,
    local_date DATE NOT NULL REFERENCES daily_challenges(local_date),
    session_id VARCHAR(36) NOT NULL,
    completed_at TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY(student_id,local_date)
);

-- Trusted victories are separate from client-reported telemetry and legacy scores.
CREATE TABLE verified_game_victories (
    session_id VARCHAR(36) PRIMARY KEY,
    student_id VARCHAR(36) NOT NULL REFERENCES users(id_user) ON DELETE CASCADE,
    game VARCHAR(20) NOT NULL CHECK(game IN ('neonflow','tetrilogic')),
    level_number INTEGER NOT NULL CHECK(level_number BETWEEN 1 AND 30),
    level_template VARCHAR(40) NOT NULL,
    activity_id VARCHAR(36) REFERENCES activities(id_activity) ON DELETE SET NULL,
    started_at TIMESTAMP WITH TIME ZONE NOT NULL,
    completed_at TIMESTAMP WITH TIME ZONE NOT NULL,
    stars INTEGER NOT NULL CHECK(stars BETWEEN 1 AND 3),
    daily_challenge_id VARCHAR(10),
    started_order BIGINT NOT NULL,
    victory_order BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    CHECK(completed_at >= started_at)
);
CREATE INDEX idx_verified_victories_student ON verified_game_victories(student_id,victory_order DESC);

CREATE TABLE achievement_xp_ledger (
    player_achievement_id VARCHAR(36) PRIMARY KEY REFERENCES player_achievements(id_player_achievement) ON DELETE CASCADE,
    student_id VARCHAR(36) NOT NULL REFERENCES users(id_user) ON DELETE CASCADE,
    session_id VARCHAR(36) NOT NULL REFERENCES verified_game_victories(session_id) ON DELETE CASCADE,
    amount INTEGER NOT NULL CHECK(amount >= 0),
    awarded_at TIMESTAMP WITH TIME ZONE NOT NULL
);
