-- Authoritative game sessions are separate from client-reported telemetry and legacy grades.
CREATE TABLE game_sessions (
    session_id VARCHAR(36) PRIMARY KEY,
    client_session_id VARCHAR(36) NOT NULL,
    student_id VARCHAR(36) NOT NULL REFERENCES users(id_user) ON DELETE CASCADE,
    active_student_id VARCHAR(36) UNIQUE,
    game VARCHAR(20) NOT NULL CHECK (game IN ('neonflow','tetrilogic')),
    level_number INTEGER NOT NULL CHECK (level_number BETWEEN 1 AND 30),
    level_template VARCHAR(40) NOT NULL,
    activity_id VARCHAR(36) REFERENCES activities(id_activity) ON DELETE SET NULL,
    daily_challenge_id TEXT,
    started_at TIMESTAMP WITH TIME ZONE NOT NULL,
    completed_at TIMESTAMP WITH TIME ZONE,
    status VARCHAR(20) NOT NULL CHECK (status IN ('ACTIVE','ABANDONED','COMPLETED')),
    state JSONB NOT NULL,
    revision INTEGER NOT NULL DEFAULT 0 CHECK (revision >= 0),
    started_order BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    stars INTEGER CHECK (stars BETWEEN 1 AND 3),
    completion_response JSONB,
    CONSTRAINT uq_game_session_client UNIQUE(student_id,client_session_id),
    CONSTRAINT ck_game_session_single_active CHECK (
        (status='ACTIVE' AND active_student_id IS NOT NULL AND active_student_id=student_id)
        OR (status<>'ACTIVE' AND active_student_id IS NULL)),
    CONSTRAINT ck_game_session_dates CHECK (completed_at IS NULL OR completed_at>=started_at),
    CONSTRAINT ck_game_session_completion CHECK (
        (status='ACTIVE' AND completed_at IS NULL AND stars IS NULL)
        OR (status='ABANDONED' AND completed_at IS NOT NULL AND stars IS NULL)
        OR (status='COMPLETED' AND completed_at IS NOT NULL AND stars IS NOT NULL))
);
CREATE INDEX idx_game_sessions_student_order ON game_sessions(student_id,started_order);
CREATE TABLE game_session_actions (
    session_id VARCHAR(36) NOT NULL REFERENCES game_sessions(session_id) ON DELETE CASCADE,
    sequence INTEGER NOT NULL CHECK (sequence > 0),
    payload_hash VARCHAR(64) NOT NULL,
    payload JSONB NOT NULL,
    received_at TIMESTAMP WITH TIME ZONE NOT NULL,
    response JSONB NOT NULL,
    PRIMARY KEY(session_id,sequence)
);
ALTER TABLE verified_game_victories ADD CONSTRAINT fk_verified_victory_session
    FOREIGN KEY(session_id) REFERENCES game_sessions(session_id) ON DELETE CASCADE;
ALTER TABLE daily_challenge_completions ADD CONSTRAINT fk_daily_completion_session
    FOREIGN KEY(session_id) REFERENCES game_sessions(session_id) ON DELETE CASCADE;
